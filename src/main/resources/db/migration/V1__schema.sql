CREATE TABLE hospital (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200)      NOT NULL,
    lat  DOUBLE PRECISION  NOT NULL,
    lng  DOUBLE PRECISION  NOT NULL
);

CREATE TABLE product (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL
);

CREATE TABLE hcp (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(200) NOT NULL,
    hospital_id BIGINT       NOT NULL,
    CONSTRAINT fk_hcp_hospital FOREIGN KEY (hospital_id) REFERENCES hospital (id)
);

CREATE TABLE visit (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hcp_id            BIGINT       NOT NULL,
    product_id        BIGINT       NOT NULL,
    department_name   VARCHAR(200) NOT NULL,
    planned_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    check_in_at       TIMESTAMP(6) WITH TIME ZONE,
    check_in_lat      DOUBLE PRECISION,
    check_in_lng      DOUBLE PRECISION,
    check_out_at      TIMESTAMP(6) WITH TIME ZONE,
    check_out_lat     DOUBLE PRECISION,
    check_out_lng     DOUBLE PRECISION,
    duration_seconds  BIGINT,
    status            VARCHAR(20)  NOT NULL,
    compliance_flag   VARCHAR(20),
    abnormal_reasons  VARCHAR(200),
    CONSTRAINT fk_visit_hcp FOREIGN KEY (hcp_id) REFERENCES hcp (id),
    CONSTRAINT fk_visit_product FOREIGN KEY (product_id) REFERENCES product (id)
);

CREATE TABLE call_report (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visit_id              BIGINT        NOT NULL,
    talking_points        VARCHAR(4000),
    feedback              VARCHAR(4000),
    materials_distributed BOOLEAN       NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_call_report_visit UNIQUE (visit_id),
    CONSTRAINT fk_call_report_visit FOREIGN KEY (visit_id) REFERENCES visit (id)
);

CREATE INDEX idx_hcp_hospital ON hcp (hospital_id);
CREATE INDEX idx_visit_hcp ON visit (hcp_id);
CREATE INDEX idx_visit_planned_at ON visit (planned_at);
